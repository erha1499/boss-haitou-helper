export const INDUSTRIES = INDUSTRY_GROUPS.flatMap(([, items]) => items);

// BOSS 一次最多同时选 3 个行业
export const INDUSTRY_BATCH_SIZE = 3;

// 只留认识的行业，按 BOSS 的顺序排，这样分批稳定
export const normalizeIndustries = (list) => (Array.isArray(list) ? INDUSTRIES.filter((name) => list.includes(name)) : []);

// 按 3 个一批分好：["a","b","c","d"] → [["a","b","c"],["d"]]；没选行业时是空数组
export function industryBatches(list) {
  const names = normalizeIndustries(list);
  const batches = [];
  for (let i = 0; i < names.length; i += INDUSTRY_BATCH_SIZE) batches.push(names.slice(i, i + INDUSTRY_BATCH_SIZE));
  return batches;
}
